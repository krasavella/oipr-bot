def normalize(text: str) -> str:
    """Ё к Е и нижний регистр — чтобы шаблоны не двоились."""
    return text.lower().replace("ё", "е")


def reply(text: str, recent: Sequence[str] = (), mood: str | None = None) -> str:
    """Ответ на реплику; recent — что уже говорилось, чтобы не повторяться."""
    topics, default = BY_MOOD.get(mood, (TOPIC_RE, DEFAULT))
    lowered = normalize(text)
    for pattern, replies in topics:
        if pattern.search(lowered):
            return _choose(replies, recent)
    return _choose(default, recent)


def working(mood: str | None, recent: Sequence[str] = ()) -> str | None:
    """Что сказать перед работой; обычному человеку — ничего."""
    replies = WORKING.get(mood or "")
    return _choose(replies, recent) if replies else None


def refusal(mood: str | None = None) -> str:
    """Отказ вместо выполненной команды; для избранного — именной."""
    return random.choice(NEMESIS_REFUSALS if mood == NEMESIS else REFUSALS)


def _choose(replies: tuple[str, ...], recent: Sequence[str]) -> str:
    """Из набора — то, чего давно не говорили; если всё сказано, любое."""
    fresh = [r for r in replies if r not in recent] or list(replies)
    return random.choice(fresh)


