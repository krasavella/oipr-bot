# как отвечать тем, к кому у бота своё отношение, — что бы они ни прислали
MOOD_OVERRIDE = {people.CRUEL: "злость", NEMESIS: "злость",
                 people.LOVED: "любовь", people.SWEET: "любовь"}


def bare(emoji: str | None) -> str:
    """Эмодзи без хвоста-селектора — иначе «☠️» и «☠» не найдут друг друга."""
    return (emoji or "").replace(VS16, "")


_MOOD_BY_EMOJI = {bare(e): name for name, incoming, _ in STICKER_MOODS for e in incoming}
_REPLY_BY_MOOD = {name: tuple(bare(e) for e in out) for name, _, out in STICKER_MOODS}


def build_stickers(pairs: Iterable[tuple[str | None, str]]) -> dict[str, list[str]]:
    """Раскладывает стикеры паков по эмодзи; под ключом ALL лежат все сразу."""
    index: dict[str, list[str]] = {ALL: []}
    for emoji, file_id in pairs:
        index.setdefault(bare(emoji), []).append(file_id)
        index[ALL].append(file_id)
    return index


def sticker_mood(emoji: str | None) -> str | None:
    """Настроение присланного стикера; незнакомое эмодзи — никакого."""
    return _MOOD_BY_EMOJI.get(bare(emoji))


def pick_sticker(index: dict[str, list[str]], emoji: str | None,
                 recent: Sequence[str] = (),
                 attitude: str | None = None) -> str | None:
    """Стикер в ответ: под настроение присланного, а не под настроение — любой."""
    if not index:
        return None
    mood = MOOD_OVERRIDE.get(attitude) or sticker_mood(emoji)
    pool = [file_id
            for wanted in _REPLY_BY_MOOD.get(mood, ())
            for file_id in index.get(wanted, ())]
    pool = pool or index[ALL]
    fresh = [f for f in pool if f not in recent] or pool
    return random.choice(fresh)
